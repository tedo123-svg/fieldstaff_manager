export const getDashboardStats = (): DashboardStats => ({
  totalMembers: MEMBERS.length,
  activeMembers: MEMBERS.filter(m => m.status === 'ACTIVE').length,
  currentlyWorking: MEMBERS.filter(m => m.todayAttendance?.status === 'PRESENT' || m.todayAttendance?.status === 'LATE').length,
  sharingLocation: MEMBERS.filter(m => m.isSharing).length,
  absentMembers: MEMBERS.filter(m => m.todayAttendance?.status === 'ABSENT').length,
  outsideAssigned: MEMBERS.filter(m => m.locationStatus === 'OUTSIDE').length,
  orgStats: ORGANIZATIONS.map(org => ({
    orgId: org.id,
    name: org.name,
    nameEn: org.nameEn,
    color: org.color,
    total: MEMBERS.filter(m => m.organizationId === org.id).length,
    active: MEMBERS.filter(m => m.organizationId === org.id && m.status === 'ACTIVE').length,
    working: MEMBERS.filter(m => m.organizationId === org.id && (m.todayAttendance?.status === 'PRESENT' || m.todayAttendance?.status === 'LATE')).length,
    absent: MEMBERS.filter(m => m.organizationId === org.id && m.todayAttendance?.status === 'ABSENT').length,
  })),
});

export const getAttendanceHistory = (): Attendance[] => {
  const records: Attendance[] = [];
  const today = new Date();
  MEMBERS.forEach(member => {
    for (let i = 0; i < 7; i++) {
      const date = new Date(today);
      date.setDate(date.getDate() - i);
      const dateStr = date.toISOString().slice(0, 10);
      const rand = Math.random();
      const status: Attendance['status'] =
        rand < 0.7 ? 'PRESENT' : rand < 0.85 ? 'LATE' : rand < 0.95 ? 'CHECKED_OUT' : 'ABSENT';
      records.push({
        id: `att-${member.id}-${i}`,
        memberId: member.id,
        member,
        date: dateStr,
        checkIn: status !== 'ABSENT' ? (status === 'LATE' ? '08:3' + Math.floor(Math.random()*9) : '08:0' + Math.floor(Math.random()*9)) : undefined,
        checkOut: status === 'CHECKED_OUT' ? '17:00' : undefined,
        status,
        createdAt: date.toISOString(),
      });
    }
  });
  return records;
};
